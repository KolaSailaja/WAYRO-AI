import type { Opportunity, StudentProfile } from "@/types";

export interface OpportunityCoachPlan {
  opportunityTitle: string;
  summary: string;
  strengths: string[];
  missingSkills: string[];
  nextSteps: string[];
  caveat: string;
}

function normalizeSkillName(value: string): string {
  return value.trim().toLowerCase();
}

export function buildOpportunityCoachPlan(
  profile: StudentProfile,
  opportunity: Opportunity,
  goal?: string
): OpportunityCoachPlan {
  const profileSkillMap = new Map(
    profile.skills.map((skill) => [normalizeSkillName(skill.name), skill.name])
  );

  const matchedSkills = opportunity.skills.filter((skill) =>
    profileSkillMap.has(normalizeSkillName(skill))
  );
  const missingSkills = opportunity.skills.filter(
    (skill) => !profileSkillMap.has(normalizeSkillName(skill))
  );

  const studentName = profile.name?.trim() || "Student";
  const goalText = goal?.trim() || "improve readiness and prepare a strong application";
  const strengthSummary =
    matchedSkills.length > 0
      ? `You already match ${matchedSkills.slice(0, 3).join(", ")}.`
      : "Your profile is strong on fit signals, but you still need to close a few requirement gaps.";

  const summary = `${studentName}, this opportunity fits best when you ${goalText}. ${strengthSummary} ${opportunity.title} is a ${opportunity.type.toLowerCase()} listing that rewards ${opportunity.skills.slice(0, 3).join(", ")}, and the connected skill gaps are actionable.`;

  const strengths = matchedSkills.length
    ? matchedSkills.slice(0, 3).map((skill) => `Strength: ${skill}`)
    : ["Strength: you have a clear student career objective and a strong reason to explore this opportunity."];

  const nextSteps = [
    missingSkills.length
      ? `Prioritise ${missingSkills.slice(0, 2).join(" and ")} to reduce the biggest readiness gap.`
      : "Keep your application materials current and ready to submit when the deadline arrives.",
    "Add evidence of your work to your profile, GitHub, and portfolio so the fit is visible to reviewers.",
    "Use the learning roadmap to build the missing skills and set a small milestone before the application window closes.",
  ];

  return {
    opportunityTitle: opportunity.title,
    summary,
    strengths,
    missingSkills: missingSkills.slice(0, 4),
    nextSteps,
    caveat:
      "This is a demo AI coaching plan generated by the local mock provider. It is not a verified selection prediction, official eligibility decision, or real AI assessment.",
  };
}
